"""Browser interaction and responsive layout checks, using demonstration data only."""
import json
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
CHECKS = []


def check(label):
    CHECKS.append(label)
    print("PASS:", label)


with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1480, "height": 1040}, device_scale_factor=1)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto("http://127.0.0.1:8767/?demo=1")
    expect(page.locator(".device-name")).to_have_count(12)
    expect(page.locator("#demo-banner")).to_be_visible()
    page.screenshot(path=str(ROOT / "preview.png"), full_page=True)
    check("dashboard loads with explicitly labelled demonstration data")

    page.locator("#asset-search").fill("AGG")
    expect(page.locator(".device-name")).to_have_count(2)
    page.locator("#asset-search").fill("")
    page.locator("#vendor-filter").select_option("hp_comware")
    expect(page.locator(".device-name")).to_have_count(4)
    page.locator("#vendor-filter").select_option("all")
    page.locator("#status-filter").select_option("fail")
    expect(page.locator(".device-name")).to_have_count(1)
    page.locator("#status-filter").select_option("all")
    expect(page.locator(".device-name")).to_have_count(12)
    check("search and vendor/status filters without pagination")

    page.locator("[data-select]").first.check()
    expect(page.locator(".selection-bar")).to_contain_text("已选择 1 台")
    page.locator("#inspect-selected").click()
    expect(page.locator("#modal")).to_contain_text("所选设备")
    page.locator("#modal [data-close]").first.click()
    page.locator("#clear-selection").click()
    page.locator(".device-name").first.click()
    expect(page.locator("#modal")).to_contain_text("命令输出（示例）")
    page.locator(".output-details").last.locator("summary").click()
    expect(page.locator(".output-details").last.locator("pre")).to_be_visible()
    page.locator("#modal").screenshot(path=str(ROOT / "detail-preview.png"))
    page.keyboard.press("Escape")
    check("device selection, scoped inspection dialog, result details and raw output")

    page.locator("[data-nav='assets']").click()
    page.locator("#add-button").click()
    page.locator("#asset-form [name='name']").fill("NEW-H3C-TEST")
    page.locator("#asset-form [name='host']").fill("192.0.2.9")
    page.locator("#asset-form [name='vendor']").select_option("hp_comware")
    page.locator("#asset-form [name='username']").fill("test-user")
    page.locator("#asset-form [name='password']").fill("test-password")
    page.locator("#save-asset").click()
    expect(page.locator("#modal")).not_to_be_visible()
    page.locator("#asset-search").fill("NEW-H3C")
    expect(page.locator(".device-name")).to_have_text("NEW-H3C-TEST")
    page.locator("[data-menu]").click()
    page.locator("#menu-edit").click()
    page.locator("#asset-form [name='name']").fill("EDITED-H3C-TEST")
    page.locator("#save-asset").click()
    page.locator("#asset-search").fill("EDITED-H3C")
    expect(page.locator(".device-name")).to_have_text("EDITED-H3C-TEST")
    page.locator("[data-menu]").click()
    page.locator("#menu-delete").click()
    page.locator("#confirm-delete").click()
    expect(page.locator(".empty-state")).to_contain_text("没有匹配的设备")
    page.locator("#clear-filters").click()
    check("add, edit and remove an H3C demonstration asset")

    page.locator("#add-button").click()
    page.locator("#asset-form [name='name']").fill("UNSPECIFIED-VENDOR")
    page.locator("#asset-form [name='host']").fill("192.0.2.10")
    page.locator("#asset-form [name='vendor']").select_option("")
    page.locator("#asset-form [name='username']").fill("test-user")
    page.locator("#asset-form [name='password']").fill("test-password")
    page.locator("#save-asset").click()
    page.locator("#asset-search").fill("UNSPECIFIED")
    expect(page.locator(".vendor")).to_have_text("未指定")
    page.locator("[data-nav='dashboard']").click()
    page.locator("#start-button").click()
    expect(page.locator("#modal")).to_contain_text("登录后执行 display version")
    page.locator("#modal [data-close]").first.click()
    page.locator("[data-nav='assets']").click()
    page.locator("#asset-search").fill("UNSPECIFIED")
    page.locator("[data-menu]").click()
    page.locator("#menu-delete").click()
    page.locator("#confirm-delete").click()
    page.locator("#clear-filters").click()
    check("save an asset without a vendor and identify it during inspection")

    page.locator("#add-button").click()
    page.locator("#tab-cidr").click()
    page.locator("#asset-form [name='cidr']").fill("192.0.2.0/30")
    page.locator("#asset-form [name='username']").fill("test-user")
    page.locator("#asset-form [name='password']").fill("test-password")
    page.locator("#save-asset").click()
    page.locator("#asset-search").fill("192.0.2.")
    expect(page.locator(".device-name")).to_have_count(2)
    check("CIDR preview interaction and valid host expansion")

    page.locator("[data-nav='settings']").click()
    page.locator("#settings-form [name='workers']").fill("3")
    page.locator("#settings-form [name='group']").fill("测试默认分组")
    page.locator("#settings-form [type='submit']").click()
    expect(page.locator("#toast")).to_contain_text("偏好已保存")
    page.screenshot(path=str(ROOT / "settings-preview.png"), full_page=True)
    page.locator("[data-nav='dashboard']").click()
    page.locator("#start-button").click()
    expect(page.locator("#run-workers")).to_have_value("3")
    page.locator("#confirm-start").click()
    expect(page.locator("#page-title")).to_have_text("巡检任务")
    expect(page.locator("#cancel-task")).to_be_visible()
    expect(page.locator(".console-pane")).to_have_count(3)
    expect(page.locator(".command-console")).to_contain_text("命令执行窗口")
    page.locator("#cancel-task").click()
    page.wait_for_function("app.data.run.state === 'cancelled'", timeout=5000)
    expect(page.locator(".task-card")).to_contain_text("已取消")
    page.locator("#start-button").click()
    page.locator("#confirm-start").click()
    page.wait_for_function("app.data.run.state === 'done'", timeout=20000)
    expect(page.locator(".task-card")).to_contain_text("已完成")
    check("session preferences, inspection launch, cancellation, restart and completion")

    page.locator("[data-nav='reports']").click()
    expect(page.locator(".archive-table tbody tr")).to_have_count(3)
    page.locator("[data-report]").first.click()
    expect(page.locator("#modal")).to_contain_text("示例巡检报告")
    page.keyboard.press("Escape")
    page.locator("[data-folder]").first.click()
    expect(page.locator("#modal")).to_contain_text("示例归档结构")
    page.keyboard.press("Escape")
    page.screenshot(path=str(ROOT / "reports-preview.png"), full_page=True)
    check("report history, report summary and archive structure")

    for width, height in [(1920,1080),(1480,1040),(1280,800),(1024,768),(980,680)]:
        page.set_viewport_size({"width":width,"height":height})
        page.locator("[data-nav='dashboard']").click()
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), (width,height)
        for nav in ["dashboard","assets","tasks","reports","settings"]:
            page.locator(f"[data-nav='{nav}']").click()
            assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), (width,height,nav)
        if width in (980,1024):
            page.locator("[data-nav='dashboard']").click()
            page.screenshot(path=str(ROOT / f"preview-{width}.png"), full_page=True)
    page.emulate_media(reduced_motion="reduce")
    assert page.evaluate("matchMedia('(prefers-reduced-motion: reduce)').matches")
    assert not errors, errors
    check("all five pages at five supported desktop sizes, reduced motion, no JavaScript errors")

    # A clean real-workspace response must render empty, and must never seed sample assets.
    clean = browser.new_page(viewport={"width":1480,"height":1040})
    clean.add_init_script("window.pywebview={api:{snapshot:async()=>({assets:[],history:[],run:{state:'idle',total:0,completed:0,results:[],logs:[],active:[]},data_dir:'isolated-test'})}};")
    clean.goto("http://127.0.0.1:8767/")
    clean.wait_for_function("typeof window.app === 'object'", timeout=5000)
    clean.evaluate("app.init()")
    expect(clean.locator(".empty-state")).to_contain_text("从第一台交换机开始")
    expect(clean.locator("#demo-banner")).not_to_be_visible()
    assert clean.evaluate("app.data.assets.length") == 0
    check("empty real workspace remains separate from demonstration mode")
    browser.close()

(ROOT / "ui-test-results.json").write_text(json.dumps({"ok":True,"checks":CHECKS},ensure_ascii=False,indent=2),encoding="utf-8")
